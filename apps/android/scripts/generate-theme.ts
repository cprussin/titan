/**
 * Writes the Compose palette from the Panda preset's primitive color tokens,
 * so the Android theme can't drift from the web's. Derived tokens (`border`,
 * `muted`, …) are `color-mix(in oklab, …)` of these, computed at runtime by
 * `OklabMix.kt` exactly as the browser does.
 *
 * Run with `bun run generate` after changing the preset.
 */
import { titanPreset } from "@titan/component-library/pandacss-preset";

const PRIMITIVES = [
  "accent",
  "background",
  "danger",
  "foreground",
  "success",
  "warning",
] as const;

type ThemedValue = { _light: string; base: string };

const colors = titanPreset.theme?.extend?.semanticTokens?.colors as Record<
  string,
  { value: ThemedValue }
>;

const hex = (value: string): string => {
  if (/^#[0-9A-Fa-f]{6}$/.test(value)) {
    return `0xFF${value.slice(1).toUpperCase()}`;
  } else {
    throw new Error(`expected a #RRGGBB color, got ${value}`);
  }
};

const palette = (pick: (value: ThemedValue) => string): string =>
  PRIMITIVES.map((name) => {
    const token = colors[name];
    if (token === undefined) {
      throw new Error(`preset has no ${name} color`);
    } else {
      return `            ${name} = ${hex(pick(token.value))},`;
    }
  }).join("\n");

const source = `// Generated by scripts/generate-theme.ts from the Panda preset. Do not edit.
package net.prussin.titan.core.theme

object TitanPalettes {
    val Dark =
        Primitives(
${palette((value) => value.base)}
        )

    val Light =
        Primitives(
${palette((value) => value._light)}
        )
}
`;

await Bun.write(
  new URL(
    "../core/src/main/kotlin/net/prussin/titan/core/theme/TitanPalettes.kt",
    import.meta.url,
  ),
  source,
);
