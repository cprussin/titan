/**
 * Converts the Phosphor icons the app uses into Android vector drawables,
 * from the same `@phosphor-icons/react` the web renders.
 *
 * Run with `bun run generate` after adding an icon to `ICONS`.
 */
import { readdir, rm } from "node:fs/promises";

const ICONS = {
  ArrowRight: ["bold"],
  ArrowsClockwise: ["regular"],
  Barbell: ["regular", "fill"],
  CaretDown: ["regular"],
  CaretLeft: ["regular"],
  CaretRight: ["regular"],
  ClockCounterClockwise: ["regular", "fill"],
  FlagCheckered: ["regular"],
  Gauge: ["regular", "fill"],
  Gear: ["regular", "fill"],
  GoogleLogo: ["bold"],
  ListChecks: ["regular"],
  MagnifyingGlass: ["regular"],
  Minus: ["regular"],
  Play: ["regular"],
  Plus: ["regular"],
  Scales: ["regular"],
  SignOut: ["regular"],
  Target: ["regular"],
  Trash: ["regular"],
  Warning: ["regular"],
} as const satisfies Record<string, readonly ("bold" | "fill" | "regular")[]>;

const defsDir = new URL(
  "./defs/",
  import.meta.resolve("@phosphor-icons/react"),
);
const outDir = new URL("../app/src/main/res/drawable/", import.meta.url);

/** The `d` of every full-opacity path in one weight's element tree. */
const pathsFor = (source: string, weight: string): string[] => {
  const start = source.indexOf(`"${weight}"`);
  if (start === -1) {
    throw new Error(`no ${weight} weight`);
  } else {
    const end = source.indexOf("\n  ]", start);
    const block = source.slice(start, end);
    if (
      /createElement\(\s*"(circle|line|rect|polyline|polygon|ellipse)"/.test(
        block,
      )
    ) {
      throw new Error(`${weight} uses a non-path element`);
    } else {
      return [...block.matchAll(/d: "([^"]+)"(?!,\s*opacity)/g)].map(
        (match) => match[1] ?? "",
      );
    }
  }
};

const snake = (name: string): string =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

const drawable = (paths: readonly string[]): string =>
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.ts from @phosphor-icons/react. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="256"
    android:viewportHeight="256">
${paths.map((d) => `    <path android:fillColor="#FF000000" android:pathData="${d}" />`).join("\n")}
</vector>
`;

for (const file of await readdir(outDir)) {
  if (file.startsWith("ph_")) {
    await rm(new URL(file, outDir));
  }
}

for (const [name, weights] of Object.entries(ICONS)) {
  const source = await Bun.file(new URL(`${name}.es.js`, defsDir)).text();
  for (const weight of weights) {
    const suffix = weight === "regular" ? "" : `_${weight}`;
    await Bun.write(
      new URL(`ph_${snake(name)}${suffix}.xml`, outDir),
      drawable(pathsFor(source, weight)),
    );
  }
}
